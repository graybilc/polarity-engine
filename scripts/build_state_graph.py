#!/usr/bin/env python3
"""CLI wrapper to generate PyTorch Geometric state graphs from mutated state dicts."""

import argparse
from pathlib import Path
import torch
from polarity_engine.builder import ProteinGraphBuilder
from polarity_engine.parsers import StructureParser


def parse_args():
    parser = argparse.ArgumentParser(description="Build PyTorch Geometric state graph.")
    parser.add_argument(
        "--input", type=Path, required=True, help="Path to input mutated state .pt file"
    )
    parser.add_argument(
        "--state-code", type=str, required=True, help="Ternary state code (e.g., '001')"
    )
    parser.add_argument(
        "--cutoff",
        type=float,
        default=8.0,
        help="Distance cutoff threshold in Angstroms",
    )
    parser.add_argument(
        "--output", type=Path, required=True, help="Output PyG graph .pt file path"
    )
    return parser.parse_args()


def main():
    args = parse_args()

    if not args.input.is_file():
        raise FileNotFoundError(
            f"Input mutated dictionary file not found: {args.input}"
        )

    # Load mutated state dictionary generated by mutate_state.py
    parsed_dict = torch.load(args.input, weights_only=False)

    # Recompute fresh rSASA for the mutated structure dictionary
    sasa_map = StructureParser._compute_allatom_sasa_dict(parsed_dict)
    parsed_dict["rsasa"] = StructureParser._compute_rsasa_vector(
        parsed_dict["nodes"], sasa_map
    )

    # Initialize ProteinGraphBuilder with interaction cutoff
    builder = ProteinGraphBuilder(distance_cutoff=args.cutoff)

    # Construct PyTorch Geometric Data object, explicitly passing recomputed rSASA
    graph_data = builder.build_from_parsed_dict(
        parsed_dict=parsed_dict,
        rsasa_np=parsed_dict["rsasa"],
        name=f"state_{args.state_code}",
    )

    # Attach state code metadata
    graph_data.state_code = args.state_code

    # Save compiled PyG Data object directly using the path argument
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(graph_data, out_path)
    print(f"[build_state_graph] Successfully built and saved PyG graph to: {out_path}")


if __name__ == "__main__":
    main()
